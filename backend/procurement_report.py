"""
STANDMAP - Standards Recommendation Report & Procurement Specification Generator
Generates decision-support ReportLab PDF reports, interactive HTML reports, and draft tender clauses
for procurement officials and technical specification drafting.
"""

import os
from typing import Dict, Any, List
from datetime import datetime
from reportlab.lib.pagesizes import letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors

def generate_tender_clause_text(analysis: Dict[str, Any], recommendations: List[Dict[str, Any]], version_checks: List[Dict[str, Any]], cert_checks: List[Dict[str, Any]]) -> str:
    lines = []
    lines.append(f"### DRAFT TENDER CLAUSE: APPLICABLE INDIAN STANDARDS & CONFORMITY REQUIREMENTS")
    lines.append(f"**Tender Reference / Item:** {analysis.get('title', 'Procurement Item')}")
    lines.append(f"**Generated by:** STANDMAP Decision-Support Platform | Date: {datetime.now().strftime('%d-%b-%Y')}\n")
    lines.append("1. **RECOMMENDED APPLICABLE INDIAN STANDARDS (Subject to Authority Verification):**")
    lines.append("The supplied equipment/materials shall conform to the applicable editions of the following Indian Standards:")
    
    seen_stds = set()
    for rec in recommendations:
        std_id = rec["standard_id"]
        if std_id in seen_stds:
            continue
        seen_stds.add(std_id)
        is_num = rec.get("is_number", std_id)
        title = rec.get("standard_title", "")
        app_stat = rec.get("applicability_status", "APPLICABLE")
        lines.append(f"- **{is_num}**: *{title}* (Status: {app_stat})")

    lines.append("\n2. **NORMATIVE & ALLIED TEST METHOD STANDARDS:**")
    for rec in recommendations[:3]:
        relationships = rec.get("relationships", [])
        for rel in relationships:
            lines.append(f"- **{rel.get('target_is')}** ({rel.get('relationship_type')}): {rel.get('target_title')} — {rel.get('description', '')}")

    if version_checks:
        lines.append("\n3. **VERSION & AMENDMENT NOTICES:**")
        for vc in version_checks:
            lines.append(f"- {vc.get('warning_message')}")

    if cert_checks:
        lines.append("\n4. **MANDATORY CERTIFICATION & QUALITY CONTROL ORDERS (QCO):**")
        for cc in cert_checks:
            lines.append(f"- **{cc.get('mandate_level')}**: {cc.get('reason')}")

    lines.append("\n5. **GENERAL COMPLIANCE NOTE:**")
    lines.append("Bidders must provide valid BIS License copies, ISI Mark certificates, and type test certificates from NABL accredited laboratories during technical bid submission.")
    
    return "\n".join(lines)

