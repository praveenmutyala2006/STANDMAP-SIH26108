def generate_pdf_report(analysis: Dict[str, Any], requirements: List[Dict[str, Any]], recommendations: List[Dict[str, Any]], version_checks: List[Dict[str, Any]], cert_checks: List[Dict[str, Any]], output_path: str):
    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    doc = SimpleDocTemplate(output_path, pagesize=letter, leftMargin=36, rightMargin=36, topMargin=36, bottomMargin=36)
    styles = getSampleStyleSheet()
    story = []
    
    title_style = ParagraphStyle(name='TitleStyle', parent=styles['Heading1'], fontSize=15, leading=18, textColor=colors.HexColor('#0f172a'))
    story.append(Paragraph(f"<b>STANDMAP Standards Recommendation Report</b>", title_style))
    story.append(Paragraph(f"Analysis ID: {analysis.get('id')} | Specification: {analysis.get('title')}", styles['Normal']))
    story.append(Paragraph(f"Organization: {analysis.get('organization')} | Category: {analysis.get('category')} | Date: {datetime.now().strftime('%Y-%m-%d %H:%M')}", styles['Normal']))
    story.append(Spacer(1, 12))
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor('#2563eb'), spaceBefore=2, spaceAfter=10))
    
    # Table of Recommendations
    story.append(Paragraph("<b>1. Recommended Indian Standards:</b>", styles['Heading3']))
    data = [["IS Number", "Standard Title", "Domain", "Applicability", "Certification Status"]]
    seen = set()
    for rec in recommendations:
        std_id = rec["standard_id"]
        if std_id in seen:
            continue
        seen.add(std_id)
        data.append([
            rec.get("is_number", std_id),
            rec.get("standard_title", "")[:35],
            rec.get("domain", "")[:25],
            rec.get("applicability_status", "APPLICABLE"),
            rec.get("certification_status", "VOLUNTARY")
        ])
        
    t = Table(data, colWidths=[80, 160, 120, 80, 95])
    t.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,0), colors.HexColor('#0f172a')),
        ('TEXTCOLOR', (0,0), (-1,0), colors.whitesmoke),
        ('ALIGN', (0,0), (-1,-1), 'LEFT'),
        ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'),
        ('FONTSIZE', (0,0), (-1,0), 8.5),
        ('BOTTOMPADDING', (0,0), (-1,0), 5),
        ('BACKGROUND', (0,1), (-1,-1), colors.HexColor('#f8fafc')),
        ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor('#cbd5e1')),
        ('FONTSIZE', (0,1), (-1,-1), 7.5),
    ]))
    story.append(t)
    story.append(Spacer(1, 14))

    # Version Warnings
    if version_checks:
        story.append(Paragraph("<b>2. Version & Amendment Findings:</b>", styles['Heading3']))
        for vc in version_checks:
            v_color = '#dc2626' if vc.get('status') == 'OUTDATED' else '#2563eb'
            story.append(Paragraph(f"<font color='{v_color}'>• <b>{vc.get('status')}</b>: {vc.get('warning_message')}</font>", styles['Normal']))
            story.append(Spacer(1, 4))
        story.append(Spacer(1, 10))

    # Certification Findings
    if cert_checks:
        story.append(Paragraph("<b>3. Statutory Certification & QCO Mandates:</b>", styles['Heading3']))
        for cc in cert_checks:
            story.append(Paragraph(f"• <b>{cc.get('mandate_level')}</b>: {cc.get('reason')}", styles['Normal']))
            story.append(Spacer(1, 4))
        story.append(Spacer(1, 10))

    story.append(Spacer(1, 10))
    story.append(Paragraph("<i>This decision-support report is generated by STANDMAP based on public BIS catalogue metadata. Procuring officials should verify final requirements against authoritative gazette notifications.</i>", styles['Italic']))
    
    doc.build(story)
    return output_path
